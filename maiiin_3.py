days = ["Пн", "Вт", "Ср", "Чт", "Пт", "Сб", "Нд"]

conversion = [5, 6, 7, 6, 8, 7, 9]
retention = [70, 72, 68, 75, 73, 71, 74]
avg_order = [200, 210, 190, 220, 205, 215, 225]
orders = [50, 55, 48, 60, 53, 57, 62]

################import matplotlib.pyplot as plt

fig, axs = plt.subplots(2, 2, figsize=(10, 8))

axs[0, 0].plot(days, conversion, marker='o', color='blue')
axs[0, 0].set_title("Конверсія (%)")
axs[0, 0].set_ylabel("%")

axs[0, 1].plot(days, retention, marker='s', color='green')
axs[0, 1].set_title("Утримання (%)")
axs[0, 1].set_ylabel("%")

axs[1, 0].plot(days, avg_order, marker='^', color='orange')
axs[1, 0].set_title("Середній чек (грн)")
axs[1, 0].set_ylabel("грн")
axs[1, 0].set_xlabel("Дні тижня")

axs[1, 1].plot(days, orders, marker='d', color='red')
axs[1, 1].set_title("Кількість замовлень")
axs[1, 1].set_ylabel("шт.")
axs[1, 1].set_xlabel("Дні тижня")

fig.suptitle("Метрики продукту за тиждень", fontsize=16)

plt.tight_layout(rect=[0, 0, 1, 0.95])
plt.show()
