# Дано дві таблиці: перша з інформацією про клієнтів ("ID", "Ім'я", "Місто"), друга — з їхніми замовленнями ("ID клієнта", "Замовлення", "Вартість").
# Створіть два DataFrame і заповніть їх не менш ніж п'ятьма рядками кожен.
# Виведіть обидва DataFrame.
# Об'єднайте їх за ідентифікатором клієнта.
# Підрахуйте загальну вартість замовлень за кожним клієнтом.
# Виведіть результат у вигляді нового DataFrame.
############Розв'язання#############################################
clients_data = {
    "ID": [1, 2, 3, 4, 5],
    "Ім'я": ["Олена", "Іван", "Марія", "Томас", "Андрій"],
    "Місто": ["Київ", "Львів", "Одеса", "Дніпро", "Харків"]
}

clients_df = pd.DataFrame(clients_data)

orders_data = {
    "ID клієнта": [1, 2, 1, 3, 4, 5, 2],
    "Замовлення": ["Ноутбук", "Телефон", "Клавіатура", "Монітор", "Принтер", "Мишка", "Навушники"],
    "Вартість": [1500, 800, 200, 300, 250, 50, 150]
}

orders_df = pd.DataFrame(orders_data)

print("Клієнти:")
print(clients_df)

print("\nЗамовлення:")
print(orders_df)

merged_df = pd.merge(orders_df, clients_df, left_on="ID клієнта", right_on="ID")
print("\nОб'єднаний DataFrame:")
print(merged_df)

total_by_client = merged_df.groupby("Ім'я")["Вартість"].sum().reset_index()
total_by_client.rename(columns={"Вартість": "Загальна вартість"}, inplace=True)

print("\nЗагальна вартість замовлень за кожним клієнтом:")
print(total_by_client)