################################# РОЗВ'ЯЗАННЯ #################################################

import numpy as np

rows, cols = map(int, input("Введіть розмірність вихідної матриці (рядки стовпці, напр. 4 6): ").split())

matrix = np.arange(1, rows * cols + 1).reshape(rows, cols)
print("\nВихідна матриця:")
print(matrix)

new_rows, new_cols = map(int, input("Введіть нові розміри матриці (рядки стовпці, напр. 2 12): ").split())

if new_rows * new_cols != rows * cols:
    print("\n Помилка: кількість елементів не співпадає, reshape неможливий!")
else:
    new_matrix = matrix.reshape(new_rows, new_cols)
    print("\nНова матриця:")
    print(new_matrix)

    min_values = np.min(new_matrix, axis=1)
    max_values = np.max(new_matrix, axis=1)
    print("\nМінімальні значення в кожному рядку:")
    print(min_values)
    print("\nМаксимальні значення в кожному рядку:")
    print(max_values)

    total_sum = np.sum(new_matrix)
    print(f"\nЗагальна сума всіх елементів: {total_sum}")

