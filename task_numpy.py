# Виведіть отриману матрицю.
# Визначте мінімальні та максимальні значення в кожному рядку нової матриці та виведіть обидва одновимірні масиви.
# Підрахуйте загальну суму всіх елементів нової матриці та виведіть результат.

####################### РОЗВ'ЯЗАННЯ ####################################################

import numpy as np

rows, cols = map(int, input("Введіть розмірність матриці (наприклад, 4 6): ").split())

matrix = np.arange(1, rows * cols + 1).reshape(rows, cols)
print("\nВихідна матриця:")
print(matrix)

new_rows, new_cols = map(int, input("Введіть нові розміри матриці (наприклад, 2 12): ").split())

reshaped_matrix = matrix.reshape(new_rows, new_cols)
print("\nМатриця після зміни розмірності:")
print(reshaped_matrix)

row_mins = np.min(reshaped_matrix, axis=1)
row_maxs = np.max(reshaped_matrix, axis=1)
print("\nМінімальні значення в кожному рядку:")
print(row_mins)
print("\nМаксимальні значення в кожному рядку:")
print(row_maxs)

total_sum = np.sum(reshaped_matrix)
print(f"\nЗагальна сума всіх елементів нової матриці: {total_sum}")
